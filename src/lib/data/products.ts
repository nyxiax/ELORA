export function getRelated(p: Product, n = 8): Product[] {
  const scored = PRODUCTS.filter((x) => x.id !== p.id).map((x) => {
    let s = 0;
    if (x.subSlug === p.subSlug) s += 4;
    if (x.group === p.group) s += 2;
    if (x.brandSlug === p.brandSlug) s += 2;
    if (x.category === p.category) s += 1;
    return { x, s };
  });
  return scored
    .sort((a, b) => b.s - a.s || b.x.rating - a.x.rating)
    .slice(0, n)
    .map(({ x }) => x);
}

/** search across name/brand/category/keywords */
export function searchProducts(query: string): Product[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return PRODUCTS.filter((p) => {
    const hay = [
      p.name,
      p.sub,
      p.group,
      p.subSlug,
      brandNameFa(p.brandSlug),
      p.brandSlug,
      p.category,
      ...p.keywords,
    ]
      .join(" ")
      .toLowerCase();
    return q.split(/\s+/).every((word) => hay.includes(word));
  });
}

